import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';

const generated=new Set(['src/client-release.ts','public/ancient-embed.html']);
const stamp=/<meta name="astrift-build" content="[^"]*">/g;
const files=['src','public'].flatMap(dir=>readdirSync(dir,{recursive:true,withFileTypes:true})
 .filter(entry=>entry.isFile()&&!entry.name.startsWith('.'))
 .map(entry=>entry.parentPath+'/'+entry.name)).filter(path=>!generated.has(path)).sort();
const hash=createHash('sha256');
for(const file of files){
 const content=readFileSync(file);
 hash.update(file).update('\0').update(file.endsWith('.html')?content.toString().replace(stamp,''):content).update('\0');
}
const version=hash.digest('hex').slice(0,20);
writeFileSync('src/client-release.ts',`// © 2026 Felix — Astrift / ASTRIFT FRONT. All rights reserved.
// Generated by scripts/build-client-version.mjs.
export const CLIENT_RELEASE = '${version}';
`);
for(const file of ['public/index.html','public/ancient.html']){
 const html=readFileSync(file,'utf8').replace(stamp,'');
 writeFileSync(file,html.replace('<head>',`<head><meta name="astrift-build" content="${version}">`));
}
console.log('Astrift client release',version);
