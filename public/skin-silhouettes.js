export function createSkinSilhouette(THREE,id,radius,plate,light){
  const spec=PROFILES[id];
  if(!spec)return null;
  const group=new THREE.Group();
  const outline=[...spec.ridge,[spec.ridge.at(-1)[0],.085],[spec.ridge[0][0],.085]];
  for(const side of [-1,1]){
    const shape=new THREE.Shape();
    outline.forEach(([z,y],i)=>i?shape.lineTo(-z,y):shape.moveTo(-z,y));
    shape.closePath();
    const geometry=new THREE.ExtrudeGeometry(shape,{depth:.026,bevelEnabled:true,bevelSize:.004,bevelThickness:.003,bevelSegments:1,curveSegments:1});
    const shell=new THREE.Mesh(geometry,plate);
    shell.rotation.y=Math.PI/2;
    shell.position.x=side*(radius+.058);
    group.add(shell);
    const [finZ,finY,finLength]=spec.fin;
    const fin=new THREE.Mesh(new THREE.BoxGeometry(.026,.024,finLength),light);
    fin.position.set(side*(radius+.095),finY,finZ);
    fin.rotation.x=side*.16;
    group.add(fin);
    const [tailLength,tailHeight]=spec.tail;
    const tail=new THREE.Mesh(new THREE.BoxGeometry(.045,.045,tailLength),plate);
    tail.position.set(side*(radius+.073),tailHeight,.24+tailLength*.2);
    tail.rotation.x=side*.11;
    group.add(tail);
  }
  group.scale.y=.72;
  group.userData.profile=id;
  return group;
}

